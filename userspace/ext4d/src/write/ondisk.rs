//! The on-disk records allocation reads and writes whole: extent tree headers and entries,
//! directory entry headers and checksum tails, and group descriptors.
//!
//! Each record is declared once, as a native struct with `#[derive(Endianize)]`
//! (`simple_endian`), which generates its little-endian `…Wire` twin; [`Record::read`] and
//! [`Record::write`] convert between the two at the byte boundary, so no field is put
//! together from bytes by hand. Fields that are split into a low and a high half on disk
//! stay split here, as the format has them; the callers join them.
//!
//! # Specification
//!
//! "Ext4 Disk Layout" on the ext4 wiki: "Extent Tree" (`ext4_extent_header`,
//! `ext4_extent_idx`, `ext4_extent`, `ext4_extent_tail`), "Directory Entries" (`ext4_dir_entry_2`,
//! `ext4_dir_entry_tail`) and "Block Group Descriptors" (`ext4_group_desc`, whose second
//! 32 bytes exist with 64-byte descriptors). Every record's size is checked when this module
//! compiles. No code here comes from the Linux kernel or from e2fsprogs.

use simple_endian::{EndianRead, EndianWrite, Endianize, read_specific, write_specific};

/// A fixed-size little-endian record in a block.
pub(super) trait Record: Sized {
    /// Its little-endian layout, generated by `Endianize`.
    type Wire: EndianRead + EndianWrite + From<Self> + Into<Self>;
    /// Its length on disk in bytes.
    const SIZE: usize;

    /// Reads the record at the start of `bytes`.
    ///
    /// # Panics
    ///
    /// If `bytes` is shorter than [`Self::SIZE`]; callers check the bounds first, as a
    /// malformed block must be refused with an error of its own.
    fn read(bytes: &[u8]) -> Self {
        assert!(
            bytes.len() >= Self::SIZE,
            "a record past the end of its block"
        );
        let wire: Self::Wire =
            read_specific(&mut &bytes[..Self::SIZE]).expect("the length was checked");
        wire.into()
    }

    /// Writes the record at the start of `bytes`.
    ///
    /// # Panics
    ///
    /// If `bytes` is shorter than [`Self::SIZE`].
    fn write(self, bytes: &mut [u8]) {
        assert!(
            bytes.len() >= Self::SIZE,
            "a record past the end of its block"
        );
        write_specific(&mut &mut bytes[..Self::SIZE], &Self::Wire::from(self))
            .expect("the length was checked");
    }
}

/// Implements [`Record`] for `$native`, whose wire type is `$wire`, `$size` bytes long.
macro_rules! record {
    ($native:ident, $wire:ident, $size:expr) => {
        impl Record for $native {
            type Wire = $wire;
            const SIZE: usize = $size;
        }
        const _: () = assert!(core::mem::size_of::<$wire>() == $size);
    };
}

/// `ext4_extent_header`: the 12 bytes at the start of every extent tree node.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Endianize)]
#[endian(le)]
#[repr(C)]
pub(super) struct ExtentHeader {
    /// `eh_magic`, `0xF30A`.
    pub(super) magic: u16,
    /// `eh_entries`: the entries in use.
    pub(super) entries: u16,
    /// `eh_max`: the entries the node has room for.
    pub(super) max: u16,
    /// `eh_depth`: 0 for a leaf.
    pub(super) depth: u16,
    /// `eh_generation`, unused.
    pub(super) generation: u32,
}
record!(ExtentHeader, ExtentHeaderWire, 12);

/// `ext4_extent`: a leaf entry.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Endianize)]
#[endian(le)]
#[repr(C)]
pub(super) struct ExtentLeaf {
    /// `ee_block`: the first file block it maps.
    pub(super) block: u32,
    /// `ee_len`: its length, plus 32768 when unwritten.
    pub(super) len: u16,
    /// `ee_start_hi`: the high 16 bits of its first volume block.
    pub(super) start_hi: u16,
    /// `ee_start_lo`: the low 32 bits.
    pub(super) start_lo: u32,
}
record!(ExtentLeaf, ExtentLeafWire, 12);

/// `ext4_extent_idx`: an index entry, naming the node below.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Endianize)]
#[endian(le)]
#[repr(C)]
pub(super) struct ExtentIndex {
    /// `ei_block`: the first file block the child covers.
    pub(super) block: u32,
    /// `ei_leaf_lo`: the low 32 bits of the child's volume block.
    pub(super) leaf_lo: u32,
    /// `ei_leaf_hi`: the high 16 bits.
    pub(super) leaf_hi: u16,
    /// `ei_unused`.
    pub(super) unused: u16,
}
record!(ExtentIndex, ExtentIndexWire, 12);

/// `ext4_extent_tail`: the checksum after a node block's last possible entry
/// (`metadata_csum`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Endianize)]
#[endian(le)]
#[repr(C)]
pub(super) struct ExtentTail {
    /// `et_checksum`.
    pub(super) checksum: u32,
}
record!(ExtentTail, ExtentTailWire, 4);

/// The 8-byte header of `ext4_dir_entry_2`, before the name. Without the `filetype` feature
/// `name_len` and `file_type` are one 16-bit name length (`ext4_dir_entry`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Endianize)]
#[endian(le)]
#[repr(C)]
pub(super) struct DirEntry {
    /// `inode`: 0 for an unused entry.
    pub(super) inode: u32,
    /// `rec_len`: the entry's length, as stored (see `crate::lookup::rec_len`).
    pub(super) rec_len: u16,
    /// `name_len`.
    pub(super) name_len: u8,
    /// `file_type`, or the high byte of the name length without `filetype`.
    pub(super) file_type: u8,
}
record!(DirEntry, DirEntryWire, 8);

/// `ext4_dir_entry_tail`: the 12 bytes ending a directory block with `metadata_csum`.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Endianize)]
#[endian(le)]
#[repr(C)]
pub(super) struct DirTail {
    /// `det_reserved_zero1`: 0, an unused entry's inode.
    pub(super) zero_inode: u32,
    /// `det_rec_len`: 12.
    pub(super) rec_len: u16,
    /// `det_reserved_zero2`: 0, a name length.
    pub(super) zero_name_len: u8,
    /// `det_reserved_ft`: `0xDE`.
    pub(super) file_type: u8,
    /// `det_checksum`.
    pub(super) checksum: u32,
}
record!(DirTail, DirTailWire, 12);

/// The first 32 bytes of `ext4_group_desc`, all a 32-byte descriptor has.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Endianize)]
#[endian(le)]
#[repr(C)]
pub(super) struct GroupDescLo {
    /// `bg_block_bitmap_lo`.
    pub(super) block_bitmap: u32,
    /// `bg_inode_bitmap_lo`.
    pub(super) inode_bitmap: u32,
    /// `bg_inode_table_lo`.
    pub(super) inode_table: u32,
    /// `bg_free_blocks_count_lo`.
    pub(super) free_blocks: u16,
    /// `bg_free_inodes_count_lo`.
    pub(super) free_inodes: u16,
    /// `bg_used_dirs_count_lo`.
    pub(super) used_dirs: u16,
    /// `bg_flags`.
    pub(super) flags: u16,
    /// `bg_exclude_bitmap_lo`.
    pub(super) exclude_bitmap: u32,
    /// `bg_block_bitmap_csum_lo`.
    pub(super) block_bitmap_csum: u16,
    /// `bg_inode_bitmap_csum_lo`.
    pub(super) inode_bitmap_csum: u16,
    /// `bg_itable_unused_lo`.
    pub(super) itable_unused: u16,
    /// `bg_checksum`.
    pub(super) checksum: u16,
}
record!(GroupDescLo, GroupDescLoWire, 32);

/// The second 32 bytes of a 64-byte `ext4_group_desc`: the high halves.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Endianize)]
#[endian(le)]
#[repr(C)]
pub(super) struct GroupDescHi {
    /// `bg_block_bitmap_hi`.
    pub(super) block_bitmap: u32,
    /// `bg_inode_bitmap_hi`.
    pub(super) inode_bitmap: u32,
    /// `bg_inode_table_hi`.
    pub(super) inode_table: u32,
    /// `bg_free_blocks_count_hi`.
    pub(super) free_blocks: u16,
    /// `bg_free_inodes_count_hi`.
    pub(super) free_inodes: u16,
    /// `bg_used_dirs_count_hi`.
    pub(super) used_dirs: u16,
    /// `bg_itable_unused_hi`.
    pub(super) itable_unused: u16,
    /// `bg_exclude_bitmap_hi`.
    pub(super) exclude_bitmap: u32,
    /// `bg_block_bitmap_csum_hi`.
    pub(super) block_bitmap_csum: u16,
    /// `bg_inode_bitmap_csum_hi`.
    pub(super) inode_bitmap_csum: u16,
    /// `bg_reserved`.
    pub(super) reserved: u32,
}
record!(GroupDescHi, GroupDescHiWire, 32);

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn records_are_little_endian_at_their_offsets() {
        let mut bytes = [0u8; 12];
        ExtentLeaf {
            block: 0x0102_0304,
            len: 0x0506,
            start_hi: 0x0708,
            start_lo: 0x090A_0B0C,
        }
        .write(&mut bytes);
        assert_eq!(bytes, [4, 3, 2, 1, 6, 5, 8, 7, 0xC, 0xB, 0xA, 9]);
        assert_eq!(ExtentLeaf::read(&bytes).start_lo, 0x090A_0B0C);
    }

    #[test]
    fn a_group_descriptor_keeps_its_fields_where_the_layout_has_them() {
        // bg_flags at 0x12, bg_checksum at 0x1E; bg_itable_unused_hi at 0x32 and
        // bg_block_bitmap_csum_hi at 0x38 (0x20 into the descriptor).
        let mut desc = [0u8; 64];
        for (i, byte) in desc.iter_mut().enumerate() {
            *byte = i as u8;
        }
        let lo = GroupDescLo::read(&desc);
        assert_eq!(lo.flags, 0x1312);
        assert_eq!(lo.checksum, 0x1F1E);
        let hi = GroupDescHi::read(&desc[32..]);
        assert_eq!(hi.itable_unused, 0x3332);
        assert_eq!(hi.block_bitmap_csum, 0x3938);
        let mut back = [0u8; 64];
        lo.write(&mut back);
        hi.write(&mut back[32..]);
        assert_eq!(back, desc);
    }

    #[test]
    #[should_panic(expected = "past the end")]
    fn a_short_buffer_panics_rather_than_reading_past_it() {
        let _ = DirEntry::read(&[0; 7]);
    }
}
