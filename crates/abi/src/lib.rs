//! Constants of the interfaces between Ferric Oxide's C library (relibc), its schemes and
//! its kernel, defined once so that every side reads the same values.
//!
//! `redox_syscall` holds the system call ABI itself. This crate holds the values that ride
//! inside calls whose meaning is fixed by POSIX rather than by the kernel: the `futimens`
//! sentinels in [`time`] and the `fchown` one in [`id`]. It also holds the files through
//! which a host's `redoxer` hands a command to the guest's `redoxerd` and reads its result,
//! in [`redoxerd`]. It is `no_std` and has no dependencies, so relibc, the kernel, daemons
//! and host tools can all use it.
//!
//! relibc's C headers are generated by cbindgen from relibc's own sources, which needs a
//! literal there; relibc asserts at compile time that its literals equal these, so the two
//! cannot drift apart.

#![no_std]
#![deny(missing_docs)]
#![forbid(unsafe_code)]

pub mod id {
    //! The owner and group sentinel of `fchown`, `chown` and `fchownat` (POSIX
    //! `<unistd.h>`).
    //!
    //! relibc passes the `uid_t` and `gid_t` arguments to the `fchown` scheme call as
    //! `u32`s, so POSIX's `(uid_t)-1` and `(gid_t)-1`, "leave this one as it is", arrive as
    //! [`UNCHANGED`].
    //!
    //! # Examples
    //!
    //! ```
    //! use ferric_abi::id::{UNCHANGED, requested};
    //!
    //! assert_eq!(requested(UNCHANGED), None);
    //! assert_eq!(requested(1000), Some(1000));
    //! ```

    /// An owner or group argument asking for it to be left as it is: `-1` as a `u32`.
    pub const UNCHANGED: u32 = u32::MAX;

    /// The owner or group `id` asks for, or `None` for [`UNCHANGED`].
    pub const fn requested(id: u32) -> Option<u32> {
        if id == UNCHANGED { None } else { Some(id) }
    }

    /// The owner and group a file has after `fchown(uid, gid)`, from its `current` owner
    /// and group: each [`UNCHANGED`] argument keeps that ID. The caller's permission to
    /// make the change is not checked here.
    ///
    /// # Examples
    ///
    /// ```
    /// use ferric_abi::id::{UNCHANGED, owner_after};
    ///
    /// assert_eq!(owner_after((1000, 100), UNCHANGED, 5), (1000, 5));
    /// ```
    pub const fn owner_after(current: (u32, u32), uid: u32, gid: u32) -> (u32, u32) {
        let uid = match requested(uid) {
            Some(uid) => uid,
            None => current.0,
        };
        let gid = match requested(gid) {
            Some(gid) => gid,
            None => current.1,
        };
        (uid, gid)
    }

    #[cfg(test)]
    mod tests {
        use super::*;

        #[test]
        fn minus_one_keeps_the_id() {
            assert_eq!(UNCHANGED, -1_i32 as u32);
            assert_eq!(requested(UNCHANGED), None);
            for id in [0, 1, 65535, 65536, u32::MAX - 1] {
                assert_eq!(requested(id), Some(id));
            }
        }

        #[test]
        fn minus_one_in_either_position_keeps_that_id() {
            for (uid, gid, expected) in [
                (UNCHANGED, UNCHANGED, (1000, 100)),
                (UNCHANGED, 5, (1000, 5)),
                (7, UNCHANGED, (7, 100)),
                (7, 5, (7, 5)),
                (0, 0, (0, 0)),
            ] {
                assert_eq!(owner_after((1000, 100), uid, gid), expected, "{uid} {gid}");
            }
        }
    }
}

pub mod time {
    //! The `tv_nsec` sentinels of `futimens` and `utimensat` (POSIX `<sys/stat.h>`).
    //!
    //! relibc passes each time as a `timespec` in the `futimens` scheme call, with these in
    //! `tv_nsec` instead of a number of nanoseconds; a null `times` pointer is sent as two
    //! [`UTIME_NOW`]s. Both are outside `0..1_000_000_000`, so they never collide with a
    //! real time.
    //!
    //! # Examples
    //!
    //! ```
    //! use ferric_abi::time::{UTIME_NOW, UTIME_OMIT, is_sentinel};
    //!
    //! assert!(is_sentinel(UTIME_NOW) && is_sentinel(UTIME_OMIT));
    //! assert!(!is_sentinel(999_999_999));
    //! ```

    /// `tv_nsec` asking for the time to be set to the current time (`tv_sec` is ignored).
    pub const UTIME_NOW: i64 = (1 << 30) - 1;
    /// `tv_nsec` asking for the time to be left as it is (`tv_sec` is ignored).
    pub const UTIME_OMIT: i64 = (1 << 30) - 2;

    // Neither can be a number of nanoseconds into a second.
    const _: () = assert!(UTIME_NOW >= 1_000_000_000 && UTIME_OMIT >= 1_000_000_000);

    /// Whether `nanoseconds` is [`UTIME_NOW`] or [`UTIME_OMIT`] rather than a time.
    pub const fn is_sentinel(nanoseconds: i64) -> bool {
        nanoseconds == UTIME_NOW || nanoseconds == UTIME_OMIT
    }

    #[cfg(test)]
    mod tests {
        use super::*;

        #[test]
        fn the_sentinels_are_the_values_relibc_has_always_sent() {
            // The encoded values are part of the ABI: changing them breaks every binary
            // built against the old ones.
            assert_eq!(UTIME_NOW, 0x3FFF_FFFF);
            assert_eq!(UTIME_OMIT, 0x3FFF_FFFE);
            for real in [0, 1, 999_999_999] {
                assert!(!is_sentinel(real));
            }
        }
    }
}

pub mod redoxerd {
    //! The files through which `redoxer` on a host runs one command in a guest and reads
    //! its result back, by way of the guest's `redoxerd`.
    //!
    //! Before booting, the host writes the command into the guest's disk at [`COMMAND`], one
    //! argument per line with the program first. Without [`CAPTURE`], `redoxerd` runs it on
    //! a terminal and echoes the terminal to the QEMU debug console, which is what a person
    //! watching `redoxer exec` wants to see.
    //!
    //! With [`CAPTURE`], the command's results are data for another program, so they must
    //! come back exactly as written: `redoxerd` runs the command without a terminal (which
    //! would merge the two streams and turn `\n` into `\r\n`), in the directory the request
    //! names, with standard output in [`STDOUT`], standard error in [`STDERR`] and its exit
    //! status in [`STATUS`], encoded as [`Outcome`]. It then flushes those files and every
    //! file under the request's sync roots to the disk before it stops the guest, so the
    //! host can read them out of the disk image once QEMU exits.
    //!
    //! # Examples
    //!
    //! ```
    //! use ferric_abi::redoxerd::{CaptureRequest, Outcome};
    //!
    //! let mut text = String::new();
    //! CaptureRequest::write(&mut text, "/src/build", ["/src/build", "/src/out.h"]).unwrap();
    //! let request = CaptureRequest::parse(&text).unwrap();
    //! assert_eq!(request.working_dir(), "/src/build");
    //! assert_eq!(request.sync_roots().collect::<Vec<_>>(), ["/src/build", "/src/out.h"]);
    //!
    //! let outcome: Outcome = "exit 2".parse().unwrap();
    //! assert_eq!(outcome, Outcome::Exited(2));
    //! assert_eq!(outcome.shell_code(), 2);
    //! ```

    use core::fmt;
    use core::str::FromStr;

    /// The command to run: the program on the first line, then one argument per line.
    pub const COMMAND: &str = "/etc/redoxerd";
    /// A [`CaptureRequest`]. Its presence is what asks for captured output.
    pub const CAPTURE: &str = "/etc/redoxerd-capture";
    /// The captured standard output.
    pub const STDOUT: &str = "/var/lib/redoxerd/stdout";
    /// The captured standard error.
    pub const STDERR: &str = "/var/lib/redoxerd/stderr";
    /// The command's [`Outcome`], as text.
    pub const STATUS: &str = "/var/lib/redoxerd/status";

    /// How a captured command ended.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum Outcome {
        /// The command exited with this status.
        Exited(i32),
        /// The command was killed by this signal.
        Signaled(i32),
    }

    impl Outcome {
        /// The status a POSIX shell reports for this outcome: the exit status, or 128
        /// plus the signal number.
        pub const fn shell_code(self) -> i32 {
            match self {
                Self::Exited(code) => code,
                Self::Signaled(signal) => 128 + signal,
            }
        }
    }

    impl fmt::Display for Outcome {
        fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
            match self {
                Self::Exited(code) => write!(f, "exit {code}"),
                Self::Signaled(signal) => write!(f, "signal {signal}"),
            }
        }
    }

    /// The [`STATUS`] text was not an [`Outcome`].
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub struct InvalidOutcome;

    impl fmt::Display for InvalidOutcome {
        fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
            f.write_str("expected \"exit <code>\" or \"signal <number>\"")
        }
    }

    impl core::error::Error for InvalidOutcome {}

    impl FromStr for Outcome {
        type Err = InvalidOutcome;

        /// Parses the text [`Outcome`]'s `Display` writes; surrounding whitespace is ignored.
        fn from_str(text: &str) -> Result<Self, Self::Err> {
            let (kind, number) = text.trim().split_once(' ').ok_or(InvalidOutcome)?;
            let number = number.parse().map_err(|_| InvalidOutcome)?;
            match kind {
                "exit" => Ok(Self::Exited(number)),
                "signal" => Ok(Self::Signaled(number)),
                _ => Err(InvalidOutcome),
            }
        }
    }

    /// The [`CAPTURE`] file: the directory the command runs in, on the first line, then
    /// the paths whose files `redoxerd` flushes to the disk afterwards, one per line.
    ///
    /// A path is a line, so a path containing a newline cannot be named; [`write`]
    /// refuses one rather than splitting it.
    ///
    /// [`write`]: CaptureRequest::write
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub struct CaptureRequest<'a> {
        working_dir: &'a str,
        sync_roots: &'a str,
    }

    impl<'a> CaptureRequest<'a> {
        /// Reads a request from the text of [`CAPTURE`], or `None` when it names no
        /// working directory.
        pub fn parse(text: &'a str) -> Option<Self> {
            let (working_dir, sync_roots) = text.split_once('\n').unwrap_or((text, ""));
            if working_dir.is_empty() {
                return None;
            }
            Some(Self {
                working_dir,
                sync_roots,
            })
        }

        /// The directory the command runs in.
        pub fn working_dir(&self) -> &'a str {
            self.working_dir
        }

        /// The files, or directories of files, to flush once the command ends.
        pub fn sync_roots(&self) -> impl Iterator<Item = &'a str> {
            self.sync_roots.lines().filter(|line| !line.is_empty())
        }

        /// Writes the request for `working_dir` and `sync_roots` to `out`.
        ///
        /// # Errors
        /// Returns [`fmt::Error`] when a path is empty or contains a newline, which the
        /// format cannot carry, or when `out` fails.
        pub fn write<'p>(
            out: &mut impl fmt::Write,
            working_dir: &str,
            sync_roots: impl IntoIterator<Item = &'p str>,
        ) -> fmt::Result {
            let line = |path: &str| {
                if path.is_empty() || path.contains('\n') {
                    Err(fmt::Error)
                } else {
                    Ok(())
                }
            };
            line(working_dir)?;
            writeln!(out, "{working_dir}")?;
            for root in sync_roots {
                line(root)?;
                writeln!(out, "{root}")?;
            }
            Ok(())
        }
    }

    #[cfg(test)]
    mod tests {
        extern crate std;

        use super::*;
        use std::string::{String, ToString};
        use std::vec::Vec;

        #[test]
        fn an_outcome_reads_back_what_it_writes() {
            for outcome in [
                Outcome::Exited(0),
                Outcome::Exited(1),
                Outcome::Exited(255),
                Outcome::Exited(-1),
                Outcome::Signaled(9),
            ] {
                assert_eq!(outcome.to_string().parse(), Ok(outcome));
            }
            assert_eq!("exit 3\n".parse(), Ok(Outcome::Exited(3)));
        }

        #[test]
        fn malformed_outcomes_are_rejected() {
            for text in ["", "exit", "exit x", "3", "stopped 1", "exit 1 2"] {
                assert_eq!(text.parse::<Outcome>(), Err(InvalidOutcome), "{text:?}");
            }
        }

        #[test]
        fn signals_report_as_a_shell_does() {
            assert_eq!(Outcome::Signaled(9).shell_code(), 137);
            assert_eq!(Outcome::Exited(7).shell_code(), 7);
        }

        #[test]
        fn a_request_round_trips() {
            let mut text = String::new();
            CaptureRequest::write(&mut text, "/a/b", ["/a/b", "/c"]).unwrap();
            assert_eq!(text, "/a/b\n/a/b\n/c\n");
            let request = CaptureRequest::parse(&text).unwrap();
            assert_eq!(request.working_dir(), "/a/b");
            assert_eq!(request.sync_roots().collect::<Vec<_>>(), ["/a/b", "/c"]);
        }

        #[test]
        fn a_request_may_have_no_sync_roots() {
            let request = CaptureRequest::parse("/w").unwrap();
            assert_eq!(request.working_dir(), "/w");
            assert_eq!(request.sync_roots().count(), 0);
            assert_eq!(CaptureRequest::parse(""), None);
            assert_eq!(CaptureRequest::parse("\n/x\n"), None);
        }

        #[test]
        fn paths_the_format_cannot_carry_are_refused() {
            let mut text = String::new();
            assert!(CaptureRequest::write(&mut text, "/a\nb", []).is_err());
            assert!(CaptureRequest::write(&mut text, "", []).is_err());
            assert!(CaptureRequest::write(&mut text, "/a", ["/b\n"]).is_err());
        }
    }
}
