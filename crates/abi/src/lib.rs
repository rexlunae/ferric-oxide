        #[test]
        fn invalid_assignments_are_refused() {
            let mut storage = [0; 64];
            let mut env = EnvBuf::new(&mut storage);
            for key in ["", "1A", "A B", "A=B", "É"] {
                assert_eq!(env.push(key, b"1"), Err(EnvError::InvalidKey), "{key:?}");
            }
            for value in [&b"a\nb"[..], b"a\rb", b"a\0"] {
                assert_eq!(env.push("A", value), Err(EnvError::InvalidValue));
                assert_eq!(env.set("A", value), Err(EnvError::InvalidValue));
            }
            assert_eq!(env.as_bytes(), b"");
        }

        #[test]
        fn a_full_buffer_is_left_as_it_was() {
            let mut storage = [0; 12];
            let mut env = EnvBuf::new(&mut storage);
            env.push("AB", b"1234").unwrap(); // 8 bytes
            assert_eq!(
                env.push("C", b"12"),
                Err(EnvError::Full {
                    needed: 5,
                    available: 4
                })
            );
            // Replacing AB frees its 8 bytes, so a 12-byte line fits and a 13-byte one does not.
            assert_eq!(
                env.set("AB", b"1234567890"),
                Err(EnvError::Full {
                    needed: 14,
                    available: 12
                })
            );
            assert_eq!(env.as_bytes(), b"AB=1234\n");
            env.set("AB", b"12345678").unwrap();
            assert_eq!(env.as_bytes(), b"AB=12345678\n");
        }

        #[test]
        fn merge_reports_malformed_lines_and_keeps_order() {
            let mut storage = [0; 128];
            let mut env = EnvBuf::new(&mut storage);
            env.push("RSDP_ADDR", b"f5a40").unwrap();
            let mut bad = Vec::new();
            let added = env
                .merge(
                    b"# harness preset\r\nFERRIC_KERNEL=trace\r\nbroken\n\nX=a\rb\nFERRIC_TRACE=sched,irq",
                    |number, line| bad.push((number, line.to_vec())),
                )
                .unwrap();
            assert_eq!(added, 2);
            // Only lines that would not read back as their assignment are skipped; nothing
            // that is skipped can make the merge fail.
            assert_eq!(bad, [(3, b"broken".to_vec()), (5, b"X=a\rb".to_vec())]);
            assert_eq!(
                env.as_bytes(),
                b"RSDP_ADDR=f5a40\nFERRIC_KERNEL=trace\nFERRIC_TRACE=sched,irq\n"
            );
        }

        #[test]
        fn merge_stops_when_full() {
            let mut storage = [0; 8];
            let mut env = EnvBuf::new(&mut storage);
            let result = env.merge(b"A=1\nB=2\nC=3\n", |_, _| {});
            assert_eq!(
                result,
                Err(EnvError::Full {
                    needed: 4,
                    available: 0
                })
            );
            assert_eq!(env.as_bytes(), b"A=1\nB=2\n");
        }
