#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mac_patch_metadata_matches_table() {
        assert_eq!(MAC_PATCH_8125B.len() % 4, 0);
        let mut version = 0u64;
        for word in &MAC_PATCH_8125B[MAC_PATCH_8125B.len() - 4..] {
            version = (version << 16) | u64::from(*word);
        }
        assert_eq!(version, MAC_PATCH_8125B_VERSION);
    }

    #[test]
    fn mac_patch_config_ends_with_breakpoint() {
        assert_eq!(
            MAC_PATCH_8125B_CONFIG.last(),
            Some(&(0xFC48, MAC_PATCH_8125B_BREAKPOINT))
        );
    }

    #[test]
    fn phy_patch_is_terminated_and_paired() {
        assert_eq!(PHY_PATCH_8125B.len() % 2, 0);
        assert_eq!(
            &PHY_PATCH_8125B[PHY_PATCH_8125B.len() - 2..],
            &[0xFFFF, 0xFFFF]
        );
    }

    #[test]
    fn ephy_config_is_the_8125b_sequence() {
        assert_eq!(EPHY_CONFIG_8125B.len(), 10);
        assert_eq!(EPHY_CONFIG_8125B[0], (0x0B, 0xA908));
        assert_eq!(EPHY_CONFIG_8125B[9], (0x69, 0xFF00));
    }
}
